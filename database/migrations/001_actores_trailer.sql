USE karenflix;
ALTER TABLE peliculas
  MODIFY COLUMN imagen_url VARCHAR(2048) NULL,
  MODIFY COLUMN rating_promedio DECIMAL(4,2) NOT NULL DEFAULT 0,
  ADD COLUMN trailer_url VARCHAR(2048) NULL AFTER imagen_url;
CREATE TABLE actores (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE pelicula_actor (
 pelicula_id INT NOT NULL,
 actor_id INT UNSIGNED NOT NULL,
 PRIMARY KEY(pelicula_id,actor_id),
 FOREIGN KEY(pelicula_id) REFERENCES peliculas(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_id) REFERENCES actores(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
